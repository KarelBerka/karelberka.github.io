"""
Modular bibliometric & GitHub metadata orchestrator.
Runs each source independently into data/metrics/<source>.json and builds js/metrics.js.

Usage:
    uv run --with certifi python scripts/sync_metrics.py --source all
    uv run --with certifi python scripts/sync_metrics.py --source openalex
    uv run --with certifi python scripts/sync_metrics.py --source bip
    uv run --with certifi python scripts/sync_metrics.py --source scholar
    uv run --with certifi python scripts/sync_metrics.py --source scopus
    uv run --with certifi python scripts/sync_metrics.py --source wos
    uv run --with certifi python scripts/sync_metrics.py --source github
    uv run --with certifi python scripts/sync_metrics.py --build-only
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from scripts.sources import (
    METRICS_DIR,
    load_cached_source_json,
    load_manual_config,
    utc_now_iso,
)
from scripts.sources import bip_scholar, github_repos, google_scholar, openalex, scopus, wos

SOURCES = {
    "openalex": ("openalex.json", openalex.fetch),
    "bip": ("bip_scholar.json", bip_scholar.fetch),
    "scholar": ("google_scholar.json", google_scholar.fetch),
    "scopus": ("scopus.json", scopus.fetch),
    "wos": ("wos.json", wos.fetch),
    "github": ("github.json", github_repos.fetch),
}


def build_js_bundle():
    cfg = load_manual_config()
    oa = load_cached_source_json("openalex.json") or {}
    bip = load_cached_source_json("bip_scholar.json") or {}
    gs = load_cached_source_json("google_scholar.json") or {}
    sc = load_cached_source_json("scopus.json") or {}
    ws = load_cached_source_json("wos.json") or {}
    gh = load_cached_source_json("github.json") or {}

    # Merge per-DOI citation & impact map
    per_paper = {}
    for doi, info in (oa.get("per_doi") or {}).items():
        per_paper.setdefault(doi, {})
        per_paper[doi]["openalex_citations"] = info.get("citations")
        per_paper[doi]["openalex_id"] = info.get("openalex_id")
        per_paper[doi]["is_oa"] = info.get("is_oa")

    for doi, info in (bip.get("per_doi") or {}).items():
        per_paper.setdefault(doi, {})
        per_paper[doi]["bip_citations"] = info.get("cc")
        per_paper[doi]["bip_3yr"] = info.get("cc_3yr")
        per_paper[doi]["bip_pop"] = info.get("pop_class")
        per_paper[doi]["bip_inf"] = info.get("inf_class")
        per_paper[doi]["bip_imp"] = info.get("imp_class")
        per_paper[doi]["bip_cc_class"] = info.get("cc_class")

    def strip_per_doi(obj):
        return {k: v for k, v in obj.items() if k != "per_doi"}

    bundle = {
        "generated_at": utc_now_iso(),
        "identifiers": cfg.get("identifiers") or {},
        "sources": {
            "wos": strip_per_doi(ws),
            "scopus": strip_per_doi(sc),
            "openalex": strip_per_doi(oa),
            "bip": strip_per_doi(bip),
            "scholar": strip_per_doi(gs),
        },
        "per_paper": per_paper,
    }

    gh_bundle = {
        "fetched_at": gh.get("fetched_at"),
        "repos": gh.get("repos") or {},
    }

    out_path = ROOT / "js" / "metrics.js"
    out_content = (
        "// Auto-generated by scripts/sync_metrics.py — do not edit manually.\n"
        f"const bibliometricsData = {json.dumps(bundle, indent=2, ensure_ascii=False)};\n\n"
        f"const githubReposMeta = {json.dumps(gh_bundle, indent=2, ensure_ascii=False)};\n"
    )
    out_path.write_text(out_content, encoding="utf-8")
    print(
        f"[Bundle] Wrote {out_path.relative_to(ROOT)} "
        f"(per_paper DOIs: {len(per_paper)}, GitHub repos: {len(gh_bundle['repos'])})"
    )


def main():
    parser = argparse.ArgumentParser(description="Sync bibliometric sources & GitHub repo metadata.")
    parser.add_argument(
        "--source",
        default="all",
        choices=["all", *SOURCES.keys()],
        help="Run a single source or all sources (default: all)",
    )
    parser.add_argument(
        "--build-only",
        action="store_true",
        help="Only rebuild js/metrics.js from existing data/metrics/*.json files",
    )
    args = parser.parse_args()

    if not args.build_only:
        targets = list(SOURCES.keys()) if args.source == "all" else [args.source]
        for key in targets:
            _, fn = SOURCES[key]
            try:
                res = fn()
                print(f"  ✓ {key:10s} -> status={res.get('status')}")
            except Exception as exc:
                print(f"  ✗ {key:10s} -> FAILED: {exc}", file=sys.stderr)

    build_js_bundle()


if __name__ == "__main__":
    main()
